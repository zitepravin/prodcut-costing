function normalizeRole(role: string): string {
  return role.startsWith('ROLE_') ? role.slice(5) : role;
}

export function hasPermission(authorities: string[] | undefined | null, permissionCode: string): boolean {
  if (!authorities?.length || !permissionCode) return false;
  for (const a of authorities) {
    const granted = ROLE_GRANTS[normalizeRole(a)];
    if (granted?.includes(permissionCode)) return true;
  }
  return false;
}

export function permissionsForRoles(authorities: string[] | undefined | null): string[] {
  if (!authorities?.length) return [];
  const set = new Set<string>();
  for (const a of authorities) {
    const granted = ROLE_GRANTS[normalizeRole(a)];
    if (granted) granted.forEach((p) => set.add(p));
  }
  return [...set];
}
