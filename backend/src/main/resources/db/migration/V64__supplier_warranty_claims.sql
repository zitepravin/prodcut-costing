-- V64: Supplier warranty claims — structured claim history (SRS quality/warranty evidence)
CREATE TABLE supplier_warranty_claim (
    claim_id CHAR(36)  NOT NULL,
    supplier_id CHAR(36)  NOT NULL,
    warranty_id CHAR(36),
    claim_date          DATE         NOT NULL,
    claim_number        VARCHAR(100),
    part_number         VARCHAR(100),
    claim_cost          DECIMAL(18, 6),
    currency_code       VARCHAR(3),
    claim_status        VARCHAR(20)  NOT NULL DEFAULT 'OPEN',
    accepted_flag       BOOLEAN,
    resolution_days     INT,
    resolution_summary  VARCHAR(1000),
    evidence_status     VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    evidence_ref        VARCHAR(255),
    verified_by CHAR(36),
    verified_at         DATETIME(6),
    notes               VARCHAR(1000),
    created_by          VARCHAR(36),
    created_at          DATETIME(6)  NOT NULL,
    updated_by          VARCHAR(36),
    updated_at          DATETIME(6),
    PRIMARY KEY (claim_id),
    INDEX idx_swc_supplier_date (supplier_id, claim_date),
    INDEX idx_swc_warranty (warranty_id),
    INDEX idx_swc_status (supplier_id, claim_status),
    CONSTRAINT fk_swc_supplier FOREIGN KEY (supplier_id) REFERENCES supplier_master (supplier_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
