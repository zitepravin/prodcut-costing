-- V39: Vendor evaluation questionnaire bank (configurable, versioned — pack 09)
CREATE TABLE vendor_question (
    question_id CHAR(36)  NOT NULL,
    question_code       VARCHAR(50)  NOT NULL,
    version_no          INT          NOT NULL DEFAULT 1,
    category            VARCHAR(40)  NOT NULL,
    question_text       VARCHAR(1000) NOT NULL,
    answer_type         VARCHAR(30)  NOT NULL,
    required_flag       BOOLEAN      NOT NULL DEFAULT TRUE,
    evidence_required   BOOLEAN      NOT NULL DEFAULT FALSE,
    mandatory_gate      BOOLEAN      NOT NULL DEFAULT FALSE,
    weight              DECIMAL(9, 4),
    scoring_rule        VARCHAR(500),
    active_flag         BOOLEAN      NOT NULL DEFAULT TRUE,
    effective_from      DATE,
    effective_to        DATE,
    created_by          VARCHAR(36),
    created_at          DATETIME(6)  NOT NULL,
    updated_by          VARCHAR(36),
    updated_at          DATETIME(6),
    PRIMARY KEY (question_id),
    UNIQUE KEY uk_vq_code_version (question_code, version_no),
    INDEX idx_vq_category_active (category, active_flag)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE vendor_questionnaire_response (
    response_id CHAR(36)  NOT NULL,
    supplier_id CHAR(36)  NOT NULL,
    question_id CHAR(36)  NOT NULL,
    question_code       VARCHAR(50)  NOT NULL,
    question_version    INT          NOT NULL,
    answer_text         VARCHAR(2000),
    answer_number       DECIMAL(18, 6),
    answer_boolean      BOOLEAN,
    answer_date         DATE,
    evidence_status     VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    evidence_ref        VARCHAR(255),
    gate_passed         BOOLEAN,
    scored_value        DECIMAL(9, 4),
    responded_at        DATETIME(6)  NOT NULL,
    responded_by        VARCHAR(36),
    created_by          VARCHAR(36),
    created_at          DATETIME(6)  NOT NULL,
    updated_by          VARCHAR(36),
    updated_at          DATETIME(6),
    PRIMARY KEY (response_id),
    INDEX idx_vqr_supplier (supplier_id, responded_at),
    INDEX idx_vqr_question (question_id),
    CONSTRAINT fk_vqr_supplier FOREIGN KEY (supplier_id) REFERENCES supplier_master (supplier_id),
    CONSTRAINT fk_vqr_question FOREIGN KEY (question_id) REFERENCES vendor_question (question_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
