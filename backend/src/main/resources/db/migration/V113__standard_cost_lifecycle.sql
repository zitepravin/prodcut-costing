-- C1 Standard Cost Lifecycle (separate from should-cost draft)

CREATE TABLE IF NOT EXISTS standard_cost (
    standard_cost_id    CHAR(36)      NOT NULL PRIMARY KEY,
    bom_node_id         CHAR(36)      NOT NULL,
    program_id          CHAR(36)      NULL,
    version_no          INT           NOT NULL DEFAULT 1,
    status              VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
    -- DRAFT | MARKED_FOR_RELEASE | RELEASED | FROZEN | SUPERSEDED
    source_type         VARCHAR(40)   NOT NULL DEFAULT 'SHOULD_COST',
    source_ref_id       CHAR(36)      NULL,
    unit_cost           DECIMAL(18,6) NOT NULL,
    currency_code       CHAR(3)       NOT NULL DEFAULT 'USD',
    material_cost       DECIMAL(18,6) NULL,
    process_cost        DECIMAL(18,6) NULL,
    tooling_cost        DECIMAL(18,6) NULL,
    packaging_cost      DECIMAL(18,6) NULL,
    overhead_cost       DECIMAL(18,6) NULL,
    sga_cost            DECIMAL(18,6) NULL,
    profit_margin       DECIMAL(18,6) NULL,
    costing_variant_id  CHAR(36)      NULL,
    plant_code          VARCHAR(40)   NULL,
    valid_from          DATE          NULL,
    valid_to            DATE          NULL,
    released_at         TIMESTAMP(6)  NULL,
    released_by         VARCHAR(36)   NULL,
    frozen_at           TIMESTAMP(6)  NULL,
    frozen_by           VARCHAR(36)   NULL,
    superseded_by_id    CHAR(36)      NULL,
    calculation_basis   VARCHAR(2000) NULL,
    notes               VARCHAR(1000) NULL,
    created_by          VARCHAR(36)   NULL,
    created_at          TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_by          VARCHAR(36)   NULL,
    updated_at          TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    KEY idx_sc_bom (bom_node_id),
    KEY idx_sc_status (status),
    KEY idx_sc_bom_status (bom_node_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
