-- V36: Vendor Selection B3 — Total Cost of Ownership calculation snapshots
CREATE TABLE supplier_tco_calculation (
    tco_id              VARCHAR(36)  NOT NULL,
    supplier_id CHAR(36)  NOT NULL,
    bom_node_id CHAR(36),
    program_id CHAR(36),
    currency_code       VARCHAR(3)   NOT NULL,
    annual_volume       DECIMAL(18, 6),
    purchase_price      DECIMAL(18, 6),
    freight             DECIMAL(18, 6),
    logistics           DECIMAL(18, 6),
    packaging           DECIMAL(18, 6),
    inventory_cost      DECIMAL(18, 6),
    quality_rejection_cost DECIMAL(18, 6),
    rework_cost         DECIMAL(18, 6),
    warranty_cost       DECIMAL(18, 6),
    service_cost        DECIMAL(18, 6),
    tooling_cost        DECIMAL(18, 6),
    other_cost          DECIMAL(18, 6),
    tco_total           DECIMAL(18, 6),
    missing_components  VARCHAR(500),
    data_complete       BOOLEAN      NOT NULL DEFAULT FALSE,
    calculation_json    LONGTEXT,
    calculated_at       DATETIME(6)  NOT NULL,
    calculated_by       VARCHAR(36),
    created_by          VARCHAR(36),
    created_at          DATETIME(6)  NOT NULL,
    updated_by          VARCHAR(36),
    updated_at          DATETIME(6),
    PRIMARY KEY (tco_id),
    INDEX idx_tco_supplier (supplier_id, calculated_at),
    INDEX idx_tco_bom (bom_node_id, calculated_at),
    CONSTRAINT fk_tco_supplier FOREIGN KEY (supplier_id) REFERENCES supplier_master (supplier_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
