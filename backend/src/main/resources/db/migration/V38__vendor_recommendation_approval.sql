-- V38: Vendor Selection B5 — recommendation ranking + human approval (AI never auto-approves)
CREATE TABLE vendor_recommendation (
    recommendation_id CHAR(36)  NOT NULL,
    sourcing_event_code VARCHAR(100),
    bom_node_id CHAR(36),
    program_id CHAR(36),
    template_id CHAR(36),
    status              VARCHAR(30)  NOT NULL DEFAULT 'DRAFT',
    recommended_supplier_id CHAR(36),
    ranking_json        LONGTEXT,
    rationale           VARCHAR(2000),
    confidence_level    VARCHAR(20),
    missing_data_summary VARCHAR(1000),
    created_by          VARCHAR(36),
    created_at          DATETIME(6)  NOT NULL,
    updated_by          VARCHAR(36),
    updated_at          DATETIME(6),
    submitted_at        DATETIME(6),
    submitted_by        VARCHAR(36),
    decided_at          DATETIME(6),
    decided_by          VARCHAR(36),
    decision_comment    VARCHAR(2000),
    override_reason     VARCHAR(2000),
    PRIMARY KEY (recommendation_id),
    INDEX idx_vr_status (status, created_at),
    INDEX idx_vr_bom (bom_node_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE vendor_recommendation_candidate (
    candidate_id CHAR(36)  NOT NULL,
    recommendation_id CHAR(36)  NOT NULL,
    supplier_id CHAR(36)  NOT NULL,
    rank_position       INT          NOT NULL,
    eligible            BOOLEAN      NOT NULL,
    overall_score       DECIMAL(9, 4),
    tco_total           DECIMAL(18, 6),
    tco_currency        VARCHAR(3),
    tco_data_complete   BOOLEAN,
    failed_gates        VARCHAR(500),
    strengths           VARCHAR(1000),
    weaknesses          VARCHAR(1000),
    evidence_notes      VARCHAR(1000),
    created_by          VARCHAR(36),
    created_at          DATETIME(6)  NOT NULL,
    updated_by          VARCHAR(36),
    updated_at          DATETIME(6),
    PRIMARY KEY (candidate_id),
    INDEX idx_vrc_rec (recommendation_id, rank_position),
    CONSTRAINT fk_vrc_rec FOREIGN KEY (recommendation_id) REFERENCES vendor_recommendation (recommendation_id),
    CONSTRAINT fk_vrc_supplier FOREIGN KEY (supplier_id) REFERENCES supplier_master (supplier_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
