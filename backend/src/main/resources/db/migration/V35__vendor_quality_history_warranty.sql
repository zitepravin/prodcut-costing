-- V35: Vendor Selection B2 — quality metrics, delivery history, warranty, guarantee evidence
CREATE TABLE supplier_quality_metric (
    metric_id CHAR(36)  NOT NULL,
    supplier_id CHAR(36)  NOT NULL,
    metric_type         VARCHAR(40)  NOT NULL,
    period_start        DATE         NOT NULL,
    period_end          DATE         NOT NULL,
    metric_value        DECIMAL(18, 6) NOT NULL,
    unit                VARCHAR(20),
    sample_size         INT,
    evidence_status     VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    evidence_ref        VARCHAR(255),
    verified_by CHAR(36),
    verified_at         DATETIME(6),
    notes               VARCHAR(1000),
    created_by          VARCHAR(36),
    created_at          DATETIME(6)  NOT NULL,
    updated_by          VARCHAR(36),
    updated_at          DATETIME(6),
    PRIMARY KEY (metric_id),
    INDEX idx_sqm_supplier_type (supplier_id, metric_type, period_end),
    CONSTRAINT fk_sqm_supplier FOREIGN KEY (supplier_id) REFERENCES supplier_master (supplier_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE supplier_delivery_metric (
    metric_id CHAR(36)  NOT NULL,
    supplier_id CHAR(36)  NOT NULL,
    period_start        DATE         NOT NULL,
    period_end          DATE         NOT NULL,
    otd_percent         DECIMAL(9, 4),
    otif_percent        DECIMAL(9, 4),
    late_delivery_count INT,
    avg_delay_days      DECIMAL(9, 2),
    evidence_status     VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    evidence_ref        VARCHAR(255),
    verified_by CHAR(36),
    verified_at         DATETIME(6),
    notes               VARCHAR(1000),
    created_by          VARCHAR(36),
    created_at          DATETIME(6)  NOT NULL,
    updated_by          VARCHAR(36),
    updated_at          DATETIME(6),
    PRIMARY KEY (metric_id),
    INDEX idx_sdm_supplier_period (supplier_id, period_end),
    CONSTRAINT fk_sdm_supplier FOREIGN KEY (supplier_id) REFERENCES supplier_master (supplier_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE supplier_warranty_term (
    warranty_id CHAR(36)  NOT NULL,
    supplier_id CHAR(36)  NOT NULL,
    duration_months     INT,
    coverage_summary    VARCHAR(1000),
    exclusions          VARCHAR(1000),
    claim_sla_days      INT,
    remedy              VARCHAR(200),
    effective_from      DATE,
    effective_to        DATE,
    claim_rate          DECIMAL(12, 6),
    historical_cost     DECIMAL(18, 6),
    currency_code       VARCHAR(3),
    evidence_status     VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    evidence_ref        VARCHAR(255),
    verified_by CHAR(36),
    verified_at         DATETIME(6),
    notes               VARCHAR(1000),
    created_by          VARCHAR(36),
    created_at          DATETIME(6)  NOT NULL,
    updated_by          VARCHAR(36),
    updated_at          DATETIME(6),
    PRIMARY KEY (warranty_id),
    INDEX idx_swt_supplier (supplier_id, effective_to),
    CONSTRAINT fk_swt_supplier FOREIGN KEY (supplier_id) REFERENCES supplier_master (supplier_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE supplier_guarantee_term (
    guarantee_id CHAR(36)  NOT NULL,
    supplier_id CHAR(36)  NOT NULL,
    guarantee_type      VARCHAR(40)  NOT NULL,
    description         VARCHAR(1000),
    period_months       INT,
    conditions_text     VARCHAR(1000),
    failure_consequence VARCHAR(1000),
    effective_from      DATE,
    effective_to        DATE,
    evidence_status     VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    evidence_ref        VARCHAR(255),
    verified_by CHAR(36),
    verified_at         DATETIME(6),
    notes               VARCHAR(1000),
    created_by          VARCHAR(36),
    created_at          DATETIME(6)  NOT NULL,
    updated_by          VARCHAR(36),
    updated_at          DATETIME(6),
    PRIMARY KEY (guarantee_id),
    INDEX idx_sgt_supplier_type (supplier_id, guarantee_type),
    CONSTRAINT fk_sgt_supplier FOREIGN KEY (supplier_id) REFERENCES supplier_master (supplier_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
