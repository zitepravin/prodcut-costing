-- V69: Supplier performance feedback intake (roadmap C3 foundation)
CREATE TABLE supplier_performance_feedback (
    feedback_id CHAR(36)  NOT NULL,
    supplier_id CHAR(36)  NOT NULL,
    bom_node_id CHAR(36),
    program_id CHAR(36),
    feedback_date       DATE         NOT NULL,
    feedback_type       VARCHAR(40)  NOT NULL,
    period_start        DATE,
    period_end          DATE,
    metric_code         VARCHAR(40),
    metric_value        DECIMAL(18, 6),
    unit                VARCHAR(20),
    narrative           VARCHAR(2000),
    source_reference    VARCHAR(255),
    evidence_status     VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    evidence_ref        VARCHAR(255),
    verified_by CHAR(36),
    verified_at         DATETIME(6),
    applied_to_history  BOOLEAN      NOT NULL DEFAULT FALSE,
    applied_at          DATETIME(6),
    notes               VARCHAR(1000),
    created_by          VARCHAR(36),
    created_at          DATETIME(6)  NOT NULL,
    updated_by          VARCHAR(36),
    updated_at          DATETIME(6),
    PRIMARY KEY (feedback_id),
    INDEX idx_spf_supplier_date (supplier_id, feedback_date),
    INDEX idx_spf_type (supplier_id, feedback_type),
    INDEX idx_spf_pending_apply (applied_to_history, evidence_status),
    CONSTRAINT fk_spf_supplier FOREIGN KEY (supplier_id) REFERENCES supplier_master (supplier_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
